#!/usr/bin/env python3
"""
Generate the Apache .htaccess redirect block from REDIRECTS.md. Prints to stdout.

    python3 htaccess-redirects.py                       # canonical host allcommercialservices.com.au
    python3 htaccess-redirects.py --host example.com.au
    python3 htaccess-redirects.py --no-canonical        # leave out the http->https / www rules
    python3 htaccess-redirects.py --pending=410         # the two cleaning-era rows as 410 instead of 301

The block goes ABOVE "# BEGIN WordPress" in public_html/.htaccess. WordPress
only rewrites between its own BEGIN/END markers, so this block survives a
permalink save.

REDIRECTS.md is the source of truth; this file only reads "## The map". It is
also imported by check-prod.sh, so the rules that are generated and the rules
that are tested come from the same parse.

Why the ?page_id=N and ?p=N rules sit first: the new install has its own page
ids, so a bare ?page_id=37 would otherwise resolve to whatever the NEW site's
page 37 is. mod_rewrite runs before WordPress sees the request.
"""
import argparse
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
MAP_FILE = HERE / "REDIRECTS.md"


def parse(path=MAP_FILE):
    """Rows of the map as dicts: sources (list), status (int), target (str|None), pending (bool)."""
    text = path.read_text()
    m = re.search(r"^## The map\s*$(.*?)^## ", text, re.S | re.M)
    if not m:
        sys.exit("REDIRECTS.md: no '## The map' section")
    rows = []
    for line in m.group(1).splitlines():
        if not line.startswith("|") or set(line.strip()) <= set("|- "):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or cells[0].lower().startswith("old url"):
            continue
        sources = re.findall(r"`([^`]+)`", cells[0])
        # Rows without a literal path (the "Anything else" 404 row, the http/www
        # canonicalisation row) are behaviours, not redirects.
        sources = [s for s in sources if s.startswith("/") or s.startswith("?")]
        if not sources:
            continue
        status = int(re.search(r"\d{3}", cells[1]).group(0))
        t = re.search(r"`([^`]+)`", cells[2])
        rows.append({
            "sources": sources,
            "status": status,
            "target": t.group(1) if t else None,
            "pending": "decision" in cells[2].lower(),
            "why": re.sub(r"[*`]", "", cells[3]) if len(cells) > 3 else "",
        })
    if not rows:
        sys.exit("REDIRECTS.md: the map has no rows")
    return rows


def expectations(rows, pending="301"):
    """(source, status, target) per source, after the --pending choice."""
    out = []
    for r in rows:
        status, target = r["status"], r["target"]
        if r["pending"] and pending == "410":
            status, target = 410, None
        for s in r["sources"]:
            out.append((s, status, target, r["pending"]))
    return out


def new_paths():
    """Every page path the new build serves, from content/pages.json."""
    pages = json.loads((HERE / "content" / "pages.json").read_text())
    by = {p["slug"]: p for p in pages}

    def path(p):
        parts = [p["slug"]]
        while by.get(parts[0], {}).get("parent"):
            parts.insert(0, by[parts[0]]["parent"])
        return "/" + "/".join(parts) + "/"

    return {"/" if p.get("front") else path(p) for p in pages}


def rules(rows, host, canonical, pending):
    exp = expectations(rows, pending)
    live = new_paths()
    out = ["# BEGIN ACS redirects (generated by websites/acs/htaccess-redirects.py from REDIRECTS.md; edit the map, not this block)",
           "<IfModule mod_rewrite.c>",
           "RewriteEngine On",
           "RewriteBase /",
           ""]
    if canonical:
        h = re.escape(host)
        out += ["# Canonical host: https, no www. Enable only once the certificate for",
                f"# {host} AND www.{host} is valid, or every visitor gets a certificate error.",
                f"RewriteCond %{{HTTP_HOST}} ^www\\.{h}$ [NC]",
                f"RewriteRule ^(.*)$ https://{host}/$1 [R=301,L]",
                # Behind a proxy/CDN %{HTTPS} is off on every request; the second condition stops a loop.
                "RewriteCond %{HTTPS} !=on",
                "RewriteCond %{HTTP:X-Forwarded-Proto} !=https",
                f"RewriteRule ^(.*)$ https://{host}/$1 [R=301,L]",
                ""]

    query, paths = [], []
    for src, status, target, is_pending in exp:
        # Apache does not allow a comment after a directive on the same line (500 error),
        # so the PENDING note is a line of its own.
        note = "# PENDING Dan: 301 to Home or 410 Gone (REDIRECTS.md, positioning decision)" if is_pending else ""
        if src.startswith("?"):
            key, val = src[1:].split("=", 1)
            query += [f"# {src} -> {status} {target or ''}".rstrip()] + ([note] if note else []) + [
                      f"RewriteCond %{{QUERY_STRING}} (^|&){re.escape(key)}={re.escape(val)}(&|$)"]
            if status == 410:
                query.append("RewriteRule ^(index\\.php)?$ - [G,L]")
            else:
                # Trailing "?" drops the old query string from the target.
                query.append(f"RewriteRule ^(index\\.php)?$ {target}? [R={status},L]")
            query.append("")
        else:
            if status == 301 and src == target:
                continue   # "/ -> /" is the same URL on the same domain; a rule would loop
            if src in live:
                print(f"warning: {src} is also a page on the new site; the redirect would hide it", file=sys.stderr)
            pat = "^" + re.escape(src.strip("/")).replace("\\-", "-") + "/?$"
            if note:
                paths.append(note)
            if status == 410:
                paths.append(f"RewriteRule {pat} - [G,L]")
            else:
                paths.append(f"RewriteRule {pat} {target} [R={status},L]")

    out += ["# Old ?page_id=N / ?p=N addresses. These must run before WordPress resolves its own ids."] + query
    out += ["# Old paths."] + paths + ["", "</IfModule>", "# END ACS redirects"]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--host", default="allcommercialservices.com.au",
                    help="canonical host, no scheme (default: allcommercialservices.com.au, same domain per Dan 12 Sep)")
    ap.add_argument("--no-canonical", action="store_true", help="leave out the https / non-www rules")
    ap.add_argument("--pending", choices=("301", "410"), default="301",
                    help="the two cleaning-era rows: 301 to Home (the map's draft) or 410 Gone")
    a = ap.parse_args()
    sys.stdout.write(rules(parse(), a.host, not a.no_canonical, a.pending))


if __name__ == "__main__":
    main()
